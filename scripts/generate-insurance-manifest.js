import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const insuranceDir = path.join(__dirname, '../public/Standby/Insurance');
const outputFile = path.join(__dirname, '../lib/insuranceManifest.ts');

const supportedExtensions = ['.png', '.jpg', '.jpeg', '.webp', '.svg', '.avif'];

export function naturalSortFiles(files) {
    return [...files].sort((a, b) => {
        const nameA = path.parse(a).name;
        const nameB = path.parse(b).name;
        const numA = parseInt(nameA, 10);
        const numB = parseInt(nameB, 10);
        
        // If both filenames are numeric numbers (e.g., "1", "10")
        if (!isNaN(numA) && !isNaN(numB) && String(numA) === nameA && String(numB) === nameB) {
            return numA - numB;
        }
        
        // Fallback to Intl / natural collation (e.g. "1.png", "2.png", "10.png")
        return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
    });
}

export function generateInsuranceManifest() {
    console.log('--- Generating SilverLine Insurance Partners Manifest ---');

    if (!fs.existsSync(insuranceDir)) {
        console.warn(`Warning: Insurance directory does not exist at ${insuranceDir}. Creating directory.`);
        fs.mkdirSync(insuranceDir, { recursive: true });
    }

    const entries = fs.readdirSync(insuranceDir);
    const validImages = entries.filter(file => {
        const ext = path.extname(file).toLowerCase();
        return supportedExtensions.includes(ext) && !file.startsWith('.');
    });

    const sortedImages = naturalSortFiles(validImages);

    const logoUrls = sortedImages.map(file => `/Standby/Insurance/${file}`);

    const fileContent = `/**
 * Generated Insurance Partners Manifest
 * --------------------------------------
 * This file is automatically generated by scripts/generate-insurance-manifest.js
 * Scans public/Standby/Insurance/ and outputs logos in natural numeric order.
 * 
 * Do not edit this file manually. Add or remove images in public/Standby/Insurance/.
 */

export const insuranceLogos: string[] = ${JSON.stringify(logoUrls, null, 2)};

export default insuranceLogos;
`;

    fs.writeFileSync(outputFile, fileContent, 'utf-8');
    console.log(`Successfully generated insurance manifest: ${logoUrls.length} logos found.`);
    if (logoUrls.length > 0) {
        console.log(`First 5 logos: ${logoUrls.slice(0, 5).join(', ')}`);
        if (logoUrls.length > 5) {
            console.log(`Last 3 logos: ${logoUrls.slice(-3).join(', ')}`);
        }
    }
    return logoUrls;
}

// Execute if run directly
if (process.argv[1] === fileURLToPath(import.meta.url)) {
    generateInsuranceManifest();
}
